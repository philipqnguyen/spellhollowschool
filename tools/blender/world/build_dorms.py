"""Builds the four dorm room shells and exports them for the client.

    blender -b --factory-startup --python tools/blender/world/build_dorms.py -- \\
        [--render] [--furnish] [--only house_a,house_c]

For each shell in dorms.py (one per house slot) it writes:

* `client/public/assets/instances/<layout id>.glb`: the room, one mesh, one
  primitive per material (about 10 draw calls), painted textures embedded;
* `client/public/assets/world/<cell>.glb`: the same file under the cell id
  that `client/public/assets/world/instances.json` lists (the contract in
  docs/architecture.md);
* `client/public/assets/instances/manifest.json` and
  `client/public/assets/world/instances.json` with bounds, triangle and
  draw-call counts, the room's point lights (most important first: the
  client may use only the first few) and an ambient (hemisphere) colour;
* `art/world/<cell>.blend`: the built scene with preview lights;
* with `--render`: review images in `art/renders/dorms/`; `--furnish` also
  renders each room dressed with the starter furniture (run
  build_furniture.py first).

The walkable and placeable data for the same rooms is generated by
dorm_layouts.py into data/world/instances/.
"""

