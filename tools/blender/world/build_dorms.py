def make_materials(shell: dorms.Shell) -> dict:
    mats = {}
    for role, spec in shell.materials.items():
        name = f"{shell.cell}_{role}"
        image = bpyutil.painted(spec.texture, spec.tex_size, name) if spec.texture else None
        mats[role] = bpyutil.principled(name, spec.base, image, spec.roughness, spec.metallic, spec.emissive,
                                        emissive_color=None if image else spec.base)
    return mats


def uv_scales(shell: dorms.Shell) -> dict:
    return {role: (1.0 if spec.uv == "fit" else 1.0 / spec.tile_m) for role, spec in shell.materials.items()}


def ordered_lights(shell: dorms.Shell) -> list[dict]:
    """Lights for the manifest, most important first (fires and lamps, then
    windows, then sconces)."""
    rank = {"stove": 0, "fire": 0, "hearth": 0, "lamp": 1}
    lights = sorted(shell.lights, key=lambda lt: (rank.get(lt["id"].split("_")[0], 2 if lt["id"].startswith("window") else 3)))
    return [{"id": lt["id"], "kind": "point", "pos": lt["pos"], "color": lt["color"], "intensity": lt["intensity"],
             "range": lt["range"], **({"ripple": lt["ripple"]} if "ripple" in lt else {})} for lt in lights]


def build_one(shell: dorms.Shell, layout_id: str, args) -> dict:
    bpyutil.reset_scene()
    mats = make_materials(shell)
    obj = bpyutil.mesh_object(shell.cell, shell.mesh, mats, uv_scale=uv_scales(shell))
    inst_path = os.path.join(args.instances, f"{layout_id}.glb")
    bpyutil.export_glb([obj], inst_path)
    os.makedirs(args.world, exist_ok=True)
    shutil.copyfile(inst_path, os.path.join(args.world, f"{shell.cell}.glb"))
    info = bpyutil.glb_info(inst_path)
    lo, hi = shell.mesh.bounds()
    entry = {
        "file": f"{layout_id}.glb",
        "cell": shell.cell,
        "bounds": {"min": [round(v, 3) for v in lo], "max": [round(v, 3) for v in hi]},
        "triangles": info["triangles"],
        "draw_calls": info["draw_calls"],
        "lights": ordered_lights(shell),
        "ambient": shell.ambient,
    }
    # Animated fire (docs/architecture.md): the room's flames; its lights at a fire flicker with it.
    room_fire = fire.noted(shell.mesh)
    if room_fire:
        entry["fire"] = room_fire
        fire.link_lights(entry["lights"], room_fire.get("fires", []))
    for lt in shell.lights:
        review.point_light(f"light_{lt['id']}", lt["pos"], lt["color"], lt["intensity"])
    if args.blend_dir:
        os.makedirs(args.blend_dir, exist_ok=True)
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(os.path.abspath(args.blend_dir), f"{shell.cell}.blend"))
    if args.render:
        render_views(shell, args.renders, "")
        if args.furnish:
            furnish(shell, args.furniture)
            render_views(shell, args.renders, "_furnished")
    print(f"{layout_id}: {info['triangles']} triangles, {info['draw_calls']} draw calls, {info['images']} images -> {inst_path}")
    return entry


def render_views(shell: dorms.Shell, out_dir: str, suffix: str) -> None:
    review.setup(shell.ambient["sky"], shell.ambient["intensity"] * 0.7)
    os.makedirs(out_dir, exist_ok=True)
    lo, hi = shell.mesh.bounds()
    sx, _, sz, _ = shell.spawn
    north = lo[2] + 0.3
    views = {
        # From the door, as a player arrives.
        "entry": ((sx, 1.62, sz + 0.9), (0.0, 1.5, north), 14),
        # From the north side back toward the door.
        "back": ((hi[0] * 0.25, 1.65, lo[2] * 0.62), (lo[0] * 0.15, 1.3, hi[2]), 14),
        # From the east toward the bed and the west wall.
        "side": ((hi[0] * 0.6, 1.7, hi[2] * 0.15), (lo[0] * 0.8, 1.6, lo[2] * 0.3), 14),
        "up": ((0.0, 1.4, hi[2] * 0.6), (0.0, hi[1], -0.4), 12),
    }
    for name, (eye, target, lens) in views.items():
        review.camera(eye, target, lens)
        review.render(os.path.join(out_dir, f"{shell.cell}_{name}{suffix}.png"), 1280, 800)


