def granted_hex(asset: str, slot: str) -> list[str]:
    """The palette colours a new character of the slot's house gets for an item."""
    with open(os.path.join(REPO, "data", "items", "catalog.json"), encoding="utf-8") as f:
        catalog = json.load(f)
    with open(os.path.join(REPO, "data", "items", "palette.json"), encoding="utf-8") as f:
        palette = json.load(f)
    house = list(palette["houses"])[ord(slot[-1]) - ord("a")]  # House::ALL order
    item = next(i for i in catalog["items"] if i["asset"] == f"furniture/{asset}")
    hex_of = {c["index"]: c["hex"] for c in palette["colours"]}
    out = []
    for ch in ("primary", "secondary", "trim"):
        idx = item["dyes"][ch]
        choice = (item.get("house_dyes") or {}).get(ch)
        if choice:
            idx = palette["houses"][house]["primary" if choice == "house_primary" else "secondary"]
        out.append(hex_of[idx])
    return out


def furnish(shell: dorms.Shell, furniture_dir: str) -> None:
    """Places the starter furniture (glbs from build_furniture.py), dyed as
    a new character of the house gets it."""
    for asset, pos, yaw in SHOWCASE[shell.slot]:
        path = os.path.join(furniture_dir, f"{asset}.glb")
        if not os.path.exists(path):
            print(f"furnish: {path} missing (run build_furniture.py)")
            continue
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=path)
        for o in set(bpy.data.objects) - before:
            if o.type != "MESH":
                continue
            # The importer already turns Y-up into Z-up; a yaw about world +Y
            # is a rotation about Blender +Z by the same angle.
            o.location = bpyutil.to_blender(pos)
            o.rotation_mode = "XYZ"
            o.rotation_euler = (0.0, 0.0, yaw)
            layer = o.data.color_attributes[0].name if o.data.color_attributes else None
            for slot_ in o.material_slots:
                mat = review.dyed_preview_material(slot_.material, granted_hex(asset, shell.slot))
                if layer:
                    for n in mat.node_tree.nodes:
                        if n.type == "VERTEX_COLOR":
                            n.layer_name = layer
                slot_.material = mat


def main() -> None:
    import pins  # tools/blender/BLENDER_VERSION

    pins.require_blender()
    ap = argparse.ArgumentParser(description="Build the dorm room shells")
    ap.add_argument("--instances", default=os.path.join(REPO, "client", "public", "assets", "instances"))
    ap.add_argument("--world", default=os.path.join(REPO, "client", "public", "assets", "world"))
    ap.add_argument("--blend-dir", default=os.path.join(REPO, "art", "world"))
    ap.add_argument("--renders", default=os.path.join(REPO, "art", "renders", "dorms"))
    ap.add_argument("--furniture", default=os.path.join(REPO, "client", "public", "assets", "furniture"))
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--furnish", action="store_true")
    ap.add_argument("--only", default=None, help="comma-separated house slots")
    args = ap.parse_args(script_args(sys.argv))
    ids = dorm_layouts.layout_ids()
    shells = dorms.build_all()
    wanted = args.only.split(",") if args.only else list(shells)
    manifest_path = os.path.join(args.instances, "manifest.json")
    world_path = os.path.join(args.world, "instances.json")
    manifest = {"version": 1, "instances": {}}
    world_entries = {}
    # Keep what other builders listed (the class and arena rooms of
    # build_school.py); a full run rebuilds every dorm entry.
    for path, target in ((manifest_path, manifest), (world_path, world_entries)):
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                target.update(json.load(f))
    if not args.only:
        dorm_ids = set(ids.values())
        manifest["instances"] = {k: v for k, v in manifest.get("instances", {}).items() if k not in dorm_ids}
        world_entries = {k: v for k, v in world_entries.items() if k not in dorm_ids}
    for slot in wanted:
        shell = shells[slot]
        lid = ids[slot]
        entry = build_one(shell, lid, args)
        manifest["instances"][lid] = entry
        world_entries[lid] = {
            "cells": [{"id": shell.cell, "file": f"{shell.cell}.glb", "bounds": entry["bounds"], "level": 0}],
            "lights": entry["lights"],
            "ambient": entry["ambient"],
            **({"fire": entry["fire"]} if "fire" in entry else {}),
        }
    os.makedirs(args.instances, exist_ok=True)
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    with open(world_path, "w", encoding="utf-8") as f:
        json.dump(dict(sorted(world_entries.items())), f, indent=2)
        f.write("\n")
    print(f"wrote {manifest_path} and {world_path}")


if __name__ == "__main__":
    main()
