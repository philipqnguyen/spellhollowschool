/// A named box of the world with a purpose. Contains a point
/// when its x and z lie inside `min..=max` and its y within them too.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Area {
    pub id: String,
    pub kind: AreaKind,
    /// Display name.
    pub name: String,
    pub min: [f32; 3],
    pub max: [f32; 3],
}

impl Area {
    pub fn contains(&self, pos: [f32; 3]) -> bool {
        (0..3).all(|k| pos[k] >= self.min[k] && pos[k] <= self.max[k])
    }
}

/// A piece of solid furniture or a prop (a [`Layout::solids`] entry, or a
/// dorm's placed furniture: [`crate::catalog::FurnitureDef::blocker`]): a box
/// centred at `at` ([x, z]) with half extents `half` along its own x and z,
/// turned by `yaw` (local +z to (sin yaw, cos yaw), as furniture and the
/// castle kit's pieces), or with `round` the ellipse inscribed in that box.
/// Ground at a point strictly inside it, at a height within `y` ([bottom,
/// top]), is not ground: movement stops at its outline as at a wall
/// ([`crate::World`]), and the Monstra Viam trail walks round its bounding box.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Blocker {
    /// What stands there (`<cell or room>/<piece>`), for reports and tests.
    pub id: String,
    pub at: [f32; 2],
    pub half: [f32; 2],
    pub y: [f32; 2],
    #[serde(default, skip_serializing_if = "is_zero")]
    pub yaw: f32,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub round: bool,
}

/// The least half thickness a [`Blocker`] blocks with (metres): a
/// footprint's samples ([`crate::movement::footprint_ground`], 0.3 m round
/// the centre) and a walk's sub-steps (0.25 m) leave no gap this wide.
pub const MIN_SOLID_HALF: f32 = 0.15;

fn is_zero(v: &f32) -> bool {
    *v == 0.0
}

impl Blocker {
    /// An axis-aligned box from `min` to `max` (x, y, z): an
    /// [`AreaKind::Solid`] area's.
    pub fn from_box(id: &str, min: [f32; 3], max: [f32; 3]) -> Blocker {
        Blocker {
            id: id.to_string(),
            at: [(min[0] + max[0]) * 0.5, (min[2] + max[2]) * 0.5],
            half: [(max[0] - min[0]) * 0.5, (max[2] - min[2]) * 0.5],
            y: [min[1], max[1]],
            yaw: 0.0,
            round: false,
        }
    }

    /// `(x, z)` in the blocker's own axes, from its centre.
    #[inline]
    pub fn local(&self, x: f32, z: f32) -> [f32; 2] {
        let (dx, dz) = (x - self.at[0], z - self.at[1]);
        if self.yaw == 0.0 {
            return [dx, dz];
        }
        let (s, c) = self.yaw.sin_cos();
        [dx * c - dz * s, dx * s + dz * c]
    }

    /// The half extents it blocks with: `half`, each at least
    /// [`MIN_SOLID_HALF`]. A thinner piece (a fence rail, a notice wall)
    /// blocks as that thick, so the walking footprint's samples and steps
    /// (`crate::movement`) can never step over it.
    #[inline]
    pub fn extent(&self) -> [f32; 2] {
        [
            self.half[0].max(MIN_SOLID_HALF),
            self.half[1].max(MIN_SOLID_HALF),
        ]
    }

    /// Whether `(x, z)` lies strictly inside its outline grown by `grow`
    /// metres (0: the outline itself, so ground on it stays ground).
    #[inline]
    pub fn holds(&self, x: f32, z: f32, grow: f32) -> bool {
        let [lx, lz] = self.local(x, z);
        let [hx, hz] = self.extent();
        let (hx, hz) = (hx + grow, hz + grow);
        if self.round {
            (lx / hx) * (lx / hx) + (lz / hz) * (lz / hz) < 1.0
        } else {
            lx.abs() < hx && lz.abs() < hz
        }
    }

    /// Whether the ground point `(x, y, z)` is inside it.
    #[inline]
    pub fn blocks(&self, x: f32, y: f32, z: f32) -> bool {
        y >= self.y[0] && y <= self.y[1] && self.holds(x, z, 0.0)
    }

    /// Its bounding box in plan: `[min x, min z, max x, max z]`.
    pub fn aabb(&self) -> [f32; 4] {
        let (s, c) = (self.yaw.sin().abs(), self.yaw.cos().abs());
        let [hx, hz] = self.extent();
        let ex = hx * c + hz * s;
        let ez = hx * s + hz * c;
        [
            self.at[0] - ex,
            self.at[1] - ez,
            self.at[0] + ex,
            self.at[1] + ez,
        ]
    }

    fn check(&self) -> Result<(), String> {
        let finite = self
            .at
            .iter()
            .chain(&self.half)
            .chain(&self.y)
            .all(|v| v.is_finite())
            && self.yaw.is_finite();
        if !finite || self.half[0] <= 0.0 || self.half[1] <= 0.0 || self.y[0] > self.y[1] {
            return Err(format!(
                "solid {:?}: finite, with positive halves and y[0] <= y[1]",
                self.id
            ));
        }
        Ok(())
    }
}

/// One hoop of a ring course. A flyer passes it by crossing the
/// disc of `radius` round `pos` that faces along `yaw` (yaw 0 faces +z, the
/// layout's convention), in either direction (`crate::ring`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Ring {
    pub id: String,
    pub pos: [f32; 3],
    #[serde(default)]
    pub yaw: f32,
    pub radius: f32,
}

/// The smallest and largest ring radius [`Layout::validate`] accepts (m).
pub const RING_RADIUS: [f32; 2] = [0.5, 6.0];

/// Named points of interest: the Owl Exchange counter, class doors, etc.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Landmark {
    pub id: String,
    pub name: String,
    pub pos: [f32; 3],
}

#[derive(Debug, thiserror::Error)]
pub enum LayoutError {
    #[error("layout JSON is invalid: {0}")]
    Json(#[from] serde_json::Error),
    #[error("layout is inconsistent: {0}")]
    Invalid(String),
}

impl Layout {
    /// Parses and validates a layout file.
    pub fn from_json(json: &str) -> Result<Layout, LayoutError> {
        let layout: Layout = serde_json::from_str(json)?;
        layout.validate()?;
        Ok(layout)
    }

    /// Parses and validates a layout, then keeps only what characters of
    /// `house` may use (see [`Layout::for_house`]).
    pub fn from_json_for_house(json: &str, house: House) -> Result<Layout, LayoutError> {
        Ok(Layout::from_json(json)?.for_house(house))
    }

    /// The layout as characters of `house` see it: surfaces and interactables
    /// gated to other houses are removed, so their doorways become walls. The
    /// result of a valid layout is valid (spawns stand on ungated ground, and
    /// interactables of `house` on surfaces it keeps).
    pub fn for_house(&self, house: House) -> Layout {
        let allowed = |gate: &Option<String>| gate.as_deref().is_none_or(|h| h == house.id());
        Layout {
            version: self.version,
            surfaces: self
                .surfaces
                .iter()
                .filter(|s| allowed(&s.house))
                .cloned()
                .collect(),
            spawns: self.spawns.clone(),
            landmarks: self.landmarks.clone(),
            interactables: self
                .interactables
                .iter()
                .filter(|i| allowed(&i.house))
                .cloned()
                .collect(),
            place_areas: self.place_areas.clone(),
            areas: self.areas.clone(),
            solids: self.solids.clone(),
            rings: self.rings.clone(),
        }
    }

    /// The moving flights, in order of their first surface in the
    /// file (`data/world/stairs.json` lists them in this order; bit `i` of a
    /// staircase state is flight `i`).
    pub fn flights(&self) -> Vec<&str> {
        let mut out: Vec<&str> = Vec::new();
        for s in &self.surfaces {
            if let Some(m) = &s.moving
                && !out.contains(&m.flight.as_str())
            {
                out.push(&m.flight);
            }
        }
        out
    }

    /// The layout with flight `i` of [`Layout::flights`] in position
    /// B where bit `i` of `state` is set, else in A: the other position's
    /// surface is left out, so its landings end at a wall. Fixed surfaces stay.
    pub fn for_stairs(&self, state: u8) -> Layout {
        let flights = self.flights();
        let keep = |s: &Surface| match &s.moving {
            None => true,
            Some(m) => {
                let i = flights.iter().position(|f| *f == m.flight).unwrap_or(0);
                let at_b = state >> i & 1 == 1;
                (m.position == StairPosition::B) == at_b
            }
        };
        Layout {
            surfaces: self.surfaces.iter().filter(|s| keep(s)).cloned().collect(),
            ..self.clone()
        }
    }

    /// The area with this id.
    pub fn area(&self, id: &str) -> Option<&Area> {
        self.areas.iter().find(|a| a.id == id)
    }

    /// The interactable with this id.
    pub fn interactable(&self, id: &str) -> Option<&Interactable> {
        self.interactables.iter().find(|i| i.id == id)
    }

    /// Checks the invariants the runtime relies on: a known schema version,
    /// unique surface ids, finite non-empty rectangles, stairs (and only stairs and grounds)
    /// carrying `y_top` and `rise`, known house ids on gates, every spawn
    /// standing on ungated walkable ground, interactables on walkable ground
    /// (gated to the house of the surface they stand on), and well-formed
    /// placeable areas.
    pub fn validate(&self) -> Result<(), LayoutError> {
        let invalid = |msg: String| Err(LayoutError::Invalid(msg));
        if self.version != LAYOUT_VERSION {
            return invalid(format!(
                "unsupported version {} (expected {LAYOUT_VERSION})",
                self.version
            ));
        }
        if self.surfaces.is_empty() {
            return invalid("no surfaces".into());
        }

        let mut ids = HashSet::with_capacity(self.surfaces.len());
        for s in &self.surfaces {
            let id = &s.id;
            if !ids.insert(id.as_str()) {
                return invalid(format!("duplicate surface id {id:?}"));
            }
            let coords = [s.min[0], s.min[1], s.max[0], s.max[1], s.y];
            if coords.iter().any(|v| !v.is_finite()) {
                return invalid(format!("surface {id:?} has a non-finite coordinate"));
            }
            if s.min[0] >= s.max[0] || s.min[1] >= s.max[1] {
                return invalid(format!("surface {id:?}: min must be < max on both axes"));
            }
            if let Some(c) = s.ceiling
                && !(c.is_finite() && c > 0.0)
            {
                return invalid(format!("surface {id:?}: ceiling must be positive"));
            }
            if let Some(h) = &s.house
                && House::from_id(h).is_none()
            {
                return invalid(format!("surface {id:?}: unknown house {h:?}"));
            }
            if s.secret && (s.house.is_some() || s.moving.is_some()) {
                return invalid(format!(
                    "surface {id:?}: a secret is never gated to a house or a moving flight"
                ));
            }
            match (s.kind, s.y_top, s.rise) {
                // Stairs, natural slopes of the grounds and bridges
                // rise along one axis.
                (
                    SurfaceKind::Stair | SurfaceKind::Grounds | SurfaceKind::Bridge,
                    Some(top),
                    Some(_),
                ) => {
                    if !top.is_finite() {
                        return invalid(format!("surface {id:?} has a non-finite y_top"));
                    }
                }
                (SurfaceKind::Stair, _, _) => {
                    return invalid(format!("stair {id:?} needs both y_top and rise"));
                }
                (_, None, None) => {}
                _ => {
                    return invalid(format!("flat surface {id:?} must not have y_top or rise"));
                }
            }
            if let Some(hf) = &s.heights {
                if s.kind != SurfaceKind::Grounds || s.y_top.is_some() || s.rise.is_some() {
                    return invalid(format!(
                        "surface {id:?}: only grounds surfaces carry heights, never with y_top or rise"
                    ));
                }
                hf.check()
                    .or_else(|e| invalid(format!("surface {id:?}: {e}")))?;
                let end = hf.end();
                let slack = EDGE_EPSILON;
                if hf.origin[0] > s.min[0] + slack
                    || hf.origin[1] > s.min[1] + slack
                    || end[0] < s.max[0] - slack
                    || end[1] < s.max[1] - slack
                {
                    return invalid(format!(
                        "surface {id:?}: its heights do not cover its rectangle"
                    ));
                }
                let lowest = hf.range().0;
                if (s.y - lowest).abs() > 0.01 {
                    return invalid(format!(
                        "surface {id:?}: y {} is not its lowest height {lowest}",
                        s.y
                    ));
                }
            }
        }
        self.check_ledges()?;
        self.check_moving()?;

        // Spawns and interactables are few, so linear scans avoid building the
        // spatial index here.
        let on_ground = |pos: [f32; 3], gate_ok: &dyn Fn(&Option<String>) -> bool| {
            let [x, y, z] = pos;
            pos.iter().all(|v| v.is_finite())
                && self.surfaces.iter().any(|s| {
                    gate_ok(&s.house)
                        && s.contains(x, z)
                        && (s.height_at(x, z) - y).abs() <= SPAWN_TOLERANCE
                })
        };
        for spawn in &self.spawns {
            if !on_ground(spawn.pos, &|gate| gate.is_none()) {
                return invalid(format!(
                    "spawn {:?} is not on ungated walkable ground",
                    spawn.id
                ));
            }
        }

        let mut ids = HashSet::with_capacity(self.interactables.len());
        for it in &self.interactables {
            let id = &it.id;
            if id.is_empty() || !ids.insert(id.as_str()) {
                return invalid(format!("interactable id {id:?} is empty or not unique"));
            }
            if let Some(h) = &it.house
                && House::from_id(h).is_none()
            {
                return invalid(format!("interactable {id:?}: unknown house {h:?}"));
            }
            if it.kind == InteractableKind::DormDoor && it.house.is_none() {
                return invalid(format!("dorm door {id:?} needs a house"));
            }
            // The Owl Order Catalogue stands in its own house's common room:
            // on that house's gated ground, never on shared floor.
            if it.kind == InteractableKind::OwlOrder
                && (it.house.is_none() || !on_ground(it.pos, &|gate| *gate == it.house))
            {
                return invalid(format!(
                    "owl order stand {id:?} needs a house and must stand in its common room"
                ));
            }
            if !(it.radius.is_finite() && it.radius > 0.0 && it.yaw.is_finite()) {
                return invalid(format!("interactable {id:?}: bad radius or yaw"));
            }
            // Reachable by the characters allowed to use it.
            if !on_ground(it.pos, &|gate| gate.is_none() || *gate == it.house) {
                return invalid(format!(
                    "interactable {id:?} is not on ground its users can walk on"
                ));
            }
        }

        let mut ids = HashSet::with_capacity(self.place_areas.len());
        for area in &self.place_areas {
            if area.id.is_empty() || !ids.insert(area.id.as_str()) {
                return invalid(format!(
                    "place area id {:?} is empty or not unique",
                    area.id
                ));
            }
            area.validate()
                .map_err(|e| LayoutError::Invalid(format!("place area {:?}: {e}", area.id)))?;
        }

        let mut ids = HashSet::with_capacity(self.areas.len());
        for area in &self.areas {
            let id = &area.id;
            if id.is_empty() || !ids.insert(id.as_str()) {
                return invalid(format!("area id {id:?} is empty or not unique"));
            }
            let ok = (0..3).all(|k| {
                area.min[k].is_finite() && area.max[k].is_finite() && area.min[k] < area.max[k]
            });
            if !ok {
                return invalid(format!("area {id:?}: min must be < max on every axis"));
            }
        }

        // Solid furniture: well formed, and no spawn stands inside one.
        let mut ids = HashSet::with_capacity(self.solids.len());
        for b in &self.solids {
            if b.id.is_empty() || !ids.insert(b.id.as_str()) {
                return invalid(format!("solid id {:?} is empty or not unique", b.id));
            }
            b.check().map_err(LayoutError::Invalid)?;
        }
        for spawn in &self.spawns {
            let [x, y, z] = spawn.pos;
            if let Some(b) = self.solids.iter().find(|b| b.blocks(x, y, z)) {
                return invalid(format!(
                    "spawn {:?} stands inside solid {:?}",
                    spawn.id, b.id
                ));
            }
        }

        // Rings stand in open sky (an airspace box, no no-fly box).
        let mut ids = HashSet::with_capacity(self.rings.len());
        for ring in &self.rings {
            let id = &ring.id;
            if id.is_empty() || !ids.insert(id.as_str()) {
                return invalid(format!("ring id {id:?} is empty or not unique"));
            }
            let finite = ring.pos.iter().all(|v| v.is_finite()) && ring.yaw.is_finite();
            if !finite || !(RING_RADIUS[0]..=RING_RADIUS[1]).contains(&ring.radius) {
                return invalid(format!(
                    "ring {id:?}: a finite place and a radius of {}-{} m",
                    RING_RADIUS[0], RING_RADIUS[1]
                ));
            }
            let inside = |kind: AreaKind| {
                self.areas
                    .iter()
                    .any(|a| a.kind == kind && a.contains(ring.pos))
            };
            if !inside(AreaKind::Airspace) || inside(AreaKind::NoFly) {
                return invalid(format!("ring {id:?} is not in open airspace"));
            }
        }
        Ok(())
    }
}

impl Layout {
    /// Only stairs move, and every moving flight has at most one
    /// surface at A and one at B (at most 8 flights: a state is a `u8`). The
    /// castle file has both ([`crate::stairs::Stairs::from_json`] checks);
    /// a layout for one staircase state ([`Layout::for_stairs`]) one.
    fn check_moving(&self) -> Result<(), LayoutError> {
        let invalid = |msg: String| Err(LayoutError::Invalid(msg));
        let flights = self.flights();
        if flights.len() > 8 {
            return invalid(format!("{} moving flights (at most 8)", flights.len()));
        }
        for s in &self.surfaces {
            if let Some(m) = &s.moving
                && (s.kind != SurfaceKind::Stair || m.flight.is_empty())
            {
                return invalid(format!("surface {:?}: only stairs move", s.id));
            }
        }
        for f in flights {
            for pos in [StairPosition::A, StairPosition::B] {
                let n = self
                    .surfaces
                    .iter()
                    .filter(|s| {
                        s.moving
                            .as_ref()
                            .is_some_and(|m| m.flight == f && m.position == pos)
                    })
                    .count();
                if n > 1 {
                    return invalid(format!(
                        "flight {f:?}: {n} surfaces at {pos:?} (at most one)"
                    ));
                }
            }
        }
        Ok(())
    }

    /// Where a heightfield surface shares an edge with a surface it
    /// connects to (their heights within a step somewhere along it), the two
    /// stay within a step all along that edge: no invisible ledge in the
    /// middle of a hill.
    fn check_ledges(&self) -> Result<(), LayoutError> {
        let step = crate::movement::MoveParams::default().step_height;
        let fields: Vec<usize> = (0..self.surfaces.len())
            .filter(|&i| self.surfaces[i].heights.is_some())
            .collect();
        for &a in &fields {
            for b in 0..self.surfaces.len() {
                if a == b || (self.surfaces[b].heights.is_some() && b < a) {
                    continue;
                }
                let (sa, sb) = (&self.surfaces[a], &self.surfaces[b]);
                let lo = [sa.min[0].max(sb.min[0]), sa.min[1].max(sb.min[1])];
                let hi = [sa.max[0].min(sb.max[0]), sa.max[1].min(sb.max[1])];
                let (w, d) = (hi[0] - lo[0], hi[1] - lo[1]);
                // A shared edge only (an overlap is not a seam), longer than a point.
                let along_x = d.abs() <= EDGE_EPSILON && w > EDGE_EPSILON;
                let along_z = w.abs() <= EDGE_EPSILON && d > EDGE_EPSILON;
                if !(along_x || along_z) {
                    continue;
                }
                let len = if along_x { w } else { d };
                let n = (len / LEDGE_SAMPLE).ceil().max(1.0) as usize;
                let points: Vec<[f32; 2]> = (0..=n)
                    .map(|k| {
                        let t = k as f32 / n as f32;
                        if along_x {
                            [lo[0] + w * t, lo[1]]
                        } else {
                            [lo[0], lo[1] + d * t]
                        }
                    })
                    .collect();
                let gap =
                    |p: &[f32; 2]| (sa.height_at(p[0], p[1]) - sb.height_at(p[0], p[1])).abs();
                if !points.iter().any(|p| gap(p) <= step) {
                    continue; // not connected: a wall between them
                }
                if let Some(p) = points.iter().find(|p| gap(p) > step + 1e-3) {
                    return Err(LayoutError::Invalid(format!(
                        "surface {:?} meets {:?} with a ledge at [{}, {}]",
                        sa.id, sb.id, p[0], p[1]
                    )));
                }
            }
        }
        Ok(())
    }
}

impl Surface {
    /// The lowest and highest ground on the surface.
    pub fn height_range(&self) -> (f32, f32) {
        if let Some(hf) = &self.heights {
            return hf.range();
        }
        let top = self.y_top.unwrap_or(self.y);
        (self.y.min(top), self.y.max(top))
    }

    /// The lowest and highest ground of the surface over the part
    /// of its rectangle inside `min..max` (`[x, z]`), or `None` when they do
    /// not overlap. Stairs and slopes are planes, so their corners bound
    /// them; a heightfield is bounded by its samples in the part (and the
    /// part's corners, which blend them).
    pub fn height_range_in(&self, min: [f32; 2], max: [f32; 2]) -> Option<(f32, f32)> {
        let lo = [min[0].max(self.min[0]), min[1].max(self.min[1])];
        let hi = [max[0].min(self.max[0]), max[1].min(self.max[1])];
        if lo[0] > hi[0] || lo[1] > hi[1] {
            return None;
        }
        let mut range = (f32::INFINITY, f32::NEG_INFINITY);
        let mut take = |h: f32| range = (range.0.min(h), range.1.max(h));
        for (x, z) in [
            (lo[0], lo[1]),
            (hi[0], lo[1]),
            (lo[0], hi[1]),
            (hi[0], hi[1]),
        ] {
            take(self.height_at(x, z));
        }
        if let Some(hf) = &self.heights {
            let (cols, rows) = (hf.cols as usize, hf.rows as usize);
            for j in 0..rows {
                let z = hf.origin[1] + hf.step * j as f32;
                if z < lo[1] || z > hi[1] {
                    continue;
                }
                for i in 0..cols {
                    let x = hf.origin[0] + hf.step * i as f32;
                    if x >= lo[0] && x <= hi[0] {
                        take(hf.h[j * cols + i]);
                    }
                }
            }
        }
        Some(range)
    }

    /// True if `(x, z)` lies inside the rectangle (edges included, widened by
    /// [`EDGE_EPSILON`]).
    #[inline]
    pub fn contains(&self, x: f32, z: f32) -> bool {
        x >= self.min[0] - EDGE_EPSILON
            && x <= self.max[0] + EDGE_EPSILON
            && z >= self.min[1] - EDGE_EPSILON
            && z <= self.max[1] + EDGE_EPSILON
    }

    /// Ground height at `(x, z)`: `y` for flat surfaces; for stairs, linear from
    /// `y` at the low end to `y_top` at the end `rise` points toward. Points
    /// outside the rectangle extrapolate along the same line. A heightfield
    /// blends its samples ([`Heights::height_at`]).
    pub fn height_at(&self, x: f32, z: f32) -> f32 {
        if let Some(hf) = &self.heights {
            return hf.height_at(x, z);
        }
        self.linear().height_at(x, z)
    }

    /// The surface's ground as the world's index stores it.
    pub(crate) fn plane(&self) -> Plane {
        match &self.heights {
            Some(hf) => Plane::Heightfield(std::sync::Arc::new(hf.clone())),
            None => Plane::Linear(self.linear()),
        }
    }

    /// The surface as a plane `y + gx * (x - base_x) + gz * (z - base_z)`
    /// (its heightfield, if any, aside).
    fn linear(&self) -> LinearPlane {
        let (Some(top), Some(rise)) = (self.y_top, self.rise) else {
            return LinearPlane {
                y: self.y,
                base_x: 0.0,
                base_z: 0.0,
                gx: 0.0,
                gz: 0.0,
            };
        };
        let dy = top - self.y;
        let (w, d) = (self.max[0] - self.min[0], self.max[1] - self.min[1]);
        let (base_x, base_z, gx, gz) = match rise {
            Rise::PosX => (self.min[0], 0.0, dy / w, 0.0),
            Rise::NegX => (self.max[0], 0.0, -dy / w, 0.0),
            Rise::PosZ => (0.0, self.min[1], 0.0, dy / d),
            Rise::NegZ => (0.0, self.max[1], 0.0, -dy / d),
        };
        LinearPlane {
            y: self.y,
            base_x,
            base_z,
            gx,
            gz,
        }
    }
}

/// A surface's ground in the world's index: a plane (flat floors, stairs,
/// sloped grounds) or a heightfield (the grounds).
#[derive(Debug, Clone)]
pub(crate) enum Plane {
    Linear(LinearPlane),
    Heightfield(std::sync::Arc<Heights>),
}

impl Plane {
    #[inline]
    pub fn height_at(&self, x: f32, z: f32) -> f32 {
        match self {
            Plane::Linear(p) => p.height_at(x, z),
            Plane::Heightfield(hf) => hf.height_at(x, z),
        }
    }
}

/// Ground height of a surface as a linear function of `(x, z)`. Measured from a
/// corner of the surface rather than the world origin so heights stay precise
/// far from the origin.
#[derive(Debug, Clone, Copy)]
pub(crate) struct LinearPlane {
    pub y: f32,
    pub base_x: f32,
    pub base_z: f32,
    pub gx: f32,
    pub gz: f32,
}

impl LinearPlane {
    #[inline]
    pub fn height_at(&self, x: f32, z: f32) -> f32 {
        self.y + self.gx * (x - self.base_x) + self.gz * (z - self.base_z)
    }
}

