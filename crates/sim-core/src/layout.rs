        assert!(err(&layout_json(&[sloped], &[])).contains("only grounds"));
        let mut short = ok.clone();
        short.heights.as_mut().unwrap().h.pop();
        assert!(err(&layout_json(&[short], &[])).contains("cols * rows"));
        let mut nan = ok.clone();
        nan.heights.as_mut().unwrap().h[3] = f32::NAN;
        assert!(Layout::from_json(&layout_json(&[nan], &[])).is_err());
        let mut small = ok.clone();
        small.max = [10.0, 6.0];
        assert!(err(&layout_json(&[small], &[])).contains("do not cover"));
        let mut low = ok.clone();
        low.y -= 0.5;
        assert!(err(&layout_json(&[low], &[])).contains("lowest height"));
        let steep = hill("st", [0.0, 0.0], [4.0, 4.0], |x, _| x * 0.7);
