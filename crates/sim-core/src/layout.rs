/// The layout schema version this crate reads.
pub const LAYOUT_VERSION: u32 = 1;

/// How far outside its rectangle a point still counts as on a surface (metres).
/// Absorbs rounding where two surfaces share an edge, so there is never a
/// hairline gap between them.
pub const EDGE_EPSILON: f32 = 1e-3;

/// How far above or below its surface a spawn may sit (metres).
const SPAWN_TOLERANCE: f32 = 0.5;

/// The steepest a heightfield may rise between two neighbouring
/// samples (rise over run, about 30 degrees). At this slope a character's
/// footprint (radius 0.3 m) spans 0.17 m of height and a 0.1 m path sample
/// 0.06 m, both well inside the 0.35 m step.
pub const MAX_GROUND_SLOPE: f32 = 0.58;

/// Spacing of the samples [`Layout::validate`] tests along an edge
/// a heightfield surface shares with a neighbour (metres).
const LEDGE_SAMPLE: f32 = 0.5;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Layout {
    /// Schema version of the layout file.
    pub version: u32,
    pub surfaces: Vec<Surface>,
    #[serde(default)]
    pub spawns: Vec<Spawn>,
    #[serde(default)]
    pub landmarks: Vec<Landmark>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub interactables: Vec<Interactable>,
    /// Instance layouts only: where furniture may be placed.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub place_areas: Vec<PlaceArea>,
    /// Named areas with a purpose (dueling areas).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub areas: Vec<Area>,
    /// Solid furniture and props (docs/architecture.md "Layouts"):
    /// the tables, counters, benches, shelves, fountains, trunks and
    /// stones standing on walkable ground, measured off the art by
    /// `tools/blender/world/solids.py` (never edited by hand). Ground inside
    /// one is not ground, as inside an [`AreaKind::Solid`] box.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub solids: Vec<Blocker>,
    /// A ring course (the Flying class's `class_pitch`), in order.
    /// `protocol::BeatPrompt::Ring { ring }` is an index into it.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub rings: Vec<Ring>,
}

