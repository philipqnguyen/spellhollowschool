/// Where a moving flight rests: A (its resting place in the layout) or B.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum StairPosition {
    A,
    B,
}

impl StairPosition {
    /// The other position.
    pub fn other(self) -> StairPosition {
        match self {
            StairPosition::A => StairPosition::B,
            StairPosition::B => StairPosition::A,
        }
    }
}

/// A heightfield: ground heights every `step` metres, `cols`
/// samples east (+x) from `origin` x and `rows` samples south (+z) from
/// `origin` z, row-major in `h` (row `j`, column `i` at `h[j * cols + i]`).
/// Between samples the height blends bilinearly; outside the grid it holds
/// the nearest edge's value.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Heights {
    /// The first sample's [x, z].
    pub origin: [f32; 2],
    pub step: f32,
    pub cols: u32,
    pub rows: u32,
    pub h: Vec<f32>,
}

impl Heights {
    /// The ground height at `(x, z)`: bilinear between the four samples
    /// around it, clamped to the grid.
    #[inline]
    pub fn height_at(&self, x: f32, z: f32) -> f32 {
        let (cols, rows) = (self.cols as usize, self.rows as usize);
        let fx = ((x - self.origin[0]) / self.step).clamp(0.0, (cols - 1) as f32);
        let fz = ((z - self.origin[1]) / self.step).clamp(0.0, (rows - 1) as f32);
        // NaN input clamps to NaN; `as usize` makes it 0 and the result NaN.
        let i = (fx as usize).min(cols - 2);
        let j = (fz as usize).min(rows - 2);
        let (tx, tz) = (fx - i as f32, fz - j as f32);
        let row = j * cols + i;
        let (h00, h10) = (self.h[row], self.h[row + 1]);
        let (h01, h11) = (self.h[row + cols], self.h[row + cols + 1]);
        let a = h00 + (h10 - h00) * tx;
        let b = h01 + (h11 - h01) * tx;
        a + (b - a) * tz
    }

    /// The lowest and highest sample.
    pub fn range(&self) -> (f32, f32) {
        self.h
            .iter()
            .fold((f32::INFINITY, f32::NEG_INFINITY), |(lo, hi), &v| {
                (lo.min(v), hi.max(v))
            })
    }

    /// The steepest rise over run between two neighbouring samples.
    pub fn max_slope(&self) -> f32 {
        let (cols, rows) = (self.cols as usize, self.rows as usize);
        let mut worst = 0.0f32;
        for j in 0..rows {
            for i in 0..cols {
                let v = self.h[j * cols + i];
                if i + 1 < cols {
                    worst = worst.max((self.h[j * cols + i + 1] - v).abs());
                }
                if j + 1 < rows {
                    worst = worst.max((self.h[(j + 1) * cols + i] - v).abs());
                }
            }
        }
        worst / self.step
    }

    /// The far corner's [x, z].
    pub fn end(&self) -> [f32; 2] {
        [
            self.origin[0] + self.step * (self.cols - 1) as f32,
            self.origin[1] + self.step * (self.rows - 1) as f32,
        ]
    }

    fn check(&self) -> Result<(), String> {
        let ok = self.origin.iter().all(|v| v.is_finite())
            && self.step.is_finite()
            && self.step > 0.0
            && self.cols >= 2
            && self.rows >= 2
            && self.h.len() == self.cols as usize * self.rows as usize
            && self.h.iter().all(|v| v.is_finite());
        if !ok {
            return Err(
                "heights need a finite origin, a positive step, at least 2 x 2 \
                        finite samples and cols * rows of them"
                    .into(),
            );
        }
        let slope = self.max_slope();
        if slope > MAX_GROUND_SLOPE {
            return Err(format!(
                "heights rise {slope:.2} per metre somewhere (at most {MAX_GROUND_SLOPE})"
            ));
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InteractableKind {
    /// In a house common room: takes a character of that house (`house` is
    /// required) into their own dorm room. Leaving the dorm brings its owner
    /// back here, at `pos` facing `yaw`.
    DormDoor,
    /// In a dorm instance: leaves the room (like `ClientMsg::LeaveInstance`).
    DormExit,
    /// A hidden exploration spot (`data/world/finds.json`
    /// gives its loot table). Searching it answers `ServerMsg::FindResult`.
    FindSpot,
    /// The knitting and sewing corner of a common room (Charms crafting).
    CraftCharms,
    /// The Transfiguration table of a common room (restyles).
    CraftTransfiguration,
    /// A cauldron (the Potions classroom): dyes, finishes, potions.
    Cauldron,
    /// The Owl Exchange counter in the Entrance Hall.
    OwlExchange,
    /// A classroom door (`data/classes/schedule.json` `door`).
    ClassDoor,
    /// The way out of a class or arena instance.
    InstanceExit,
    /// A common room's notice board. The client opens the House
    /// Cup panel and the house's next classes; the server answers
    /// `Interact` with nothing and never fails it.
    NoticeBoard,
    /// The Owl Loft's owl mail. The client opens the mail panel; the
    /// server answers like a notice board (nothing, never a failure).
    OwlMail,
    /// The Wishing Room's door on the seventh-floor east
    /// corridor's blank wall. Secret: it shows only for a character the
    /// server has opened it for (`ServerMsg::WishingRoomDoor`); the client
    /// then offers the room choice and sends `ClientMsg::EnterWishingRoom`.
    /// `Interact` with it is answered like a notice board (nothing).
    WishingRoomDoor,
    /// The Owl Order Catalogue's stand in a house common room (`house` is
    /// required): a station grant for the owl-order catalogue, whose HTTP
    /// routes refuse anyone not standing at their own house's stand.
    OwlOrder,
}

impl InteractableKind {
    /// The station a crafting or Exchange interactable opens.
    pub fn station(self) -> Option<protocol::StationKind> {
        use protocol::StationKind as S;
        match self {
            InteractableKind::CraftCharms => Some(S::CraftCharms),
            InteractableKind::CraftTransfiguration => Some(S::CraftTransfiguration),
            InteractableKind::Cauldron => Some(S::Cauldron),
            InteractableKind::OwlExchange => Some(S::OwlExchange),
            InteractableKind::OwlOrder => Some(S::OwlOrder),
            InteractableKind::DormDoor
            | InteractableKind::DormExit
            | InteractableKind::FindSpot
            | InteractableKind::ClassDoor
            | InteractableKind::InstanceExit
            | InteractableKind::NoticeBoard
            | InteractableKind::OwlMail
            | InteractableKind::WishingRoomDoor => None,
        }
    }
}

/// Something a player uses with `ClientMsg::Interact { target: id }` while
/// standing within `radius` of `pos` (horizontal distance, same floor).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Interactable {
    /// Unique within the layout, stable (clients send it).
    pub id: String,
    pub kind: InteractableKind,
    /// Only this house may use it (lower-case id); `None` means everyone.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub house: Option<String>,
    /// The interaction point, on walkable ground. Characters arriving through
    /// this interactable (an owner leaving their dorm) appear here.
    pub pos: [f32; 3],
    /// Facing of arriving characters (radians, yaw 0 faces +Z).
    #[serde(default)]
    pub yaw: f32,
    /// Reach in metres.
    pub radius: f32,
    /// Prompt shown by the client ("Dormitories"); display text only.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
}

/// How far above or below an interactable a character may stand and still
/// reach it (metres): the same floor, not the one above.
pub const INTERACT_HEIGHT_TOLERANCE: f32 = 1.5;

impl Interactable {
    /// Whether a character at `pos` can use it: within `radius` horizontally
    /// and [`INTERACT_HEIGHT_TOLERANCE`] vertically. The server checks this on
    /// `ClientMsg::Interact`; the client uses it to show the prompt.
    pub fn in_reach(&self, pos: [f32; 3]) -> bool {
        let (dx, dz) = (pos[0] - self.pos[0], pos[2] - self.pos[2]);
        dx * dx + dz * dz <= self.radius * self.radius
            && (pos[1] - self.pos[1]).abs() <= INTERACT_HEIGHT_TOLERANCE
    }
}

