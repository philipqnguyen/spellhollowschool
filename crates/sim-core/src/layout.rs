#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Surface {
    /// Unique, stable id, e.g. "entrance_hall".
    pub id: String,
    pub kind: SurfaceKind,
    /// Display name for maps and debugging.
    pub name: String,
    /// Floor level index for the map and floor-aware visibility (0 = ground floor).
    pub level: i32,
    /// Streaming cell this surface's geometry belongs to.
    pub cell: String,
    /// Rectangle corners in the XZ plane: min = [x, z], max = [x, z].
    pub min: [f32; 2],
    pub max: [f32; 2],
    /// Ground height for flat surfaces; for stairs, the height at the low end.
    pub y: f32,
    /// Stairs and sloped grounds only: height at the high end and the direction it rises toward.
    #[serde(default)]
    pub y_top: Option<f32>,
    #[serde(default)]
    pub rise: Option<Rise>,
    /// Ceiling height above `y` used by the greybox generator for walls (metres).
    /// `None` means open to the sky (courtyards, grounds, bridges).
    #[serde(default)]
    pub ceiling: Option<f32>,
    /// House gate: only characters of this house (lower-case id) may walk here.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub house: Option<String>,
    /// Grounds only: the ground's heights on a grid covering the
    /// rectangle (instead of `y_top` / `rise`). `y` is then the lowest of
    /// them.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub heights: Option<Heights>,
    /// Stairs only: which moving flight this is and in which of its
    /// two positions (`None`: fixed ground, there in every staircase state).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub moving: Option<Moving>,
    /// Part of a hidden passage (`data/world/secrets.json`): walkable
    /// like any ground, never on the Monstra Viam trail, never on the map until
    /// found. Never gated to a house, never a moving flight.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub secret: bool,
}

