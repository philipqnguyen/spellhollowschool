    /// Two hills meeting along an edge connect only where they agree all
    /// along it; a seam that matches in places but drops elsewhere is a
    /// ledge, which validation refuses. Surfaces far apart in height (a
    /// cellar under the grounds) are a wall, not a ledge.
    #[test]
    fn heightfield_seams_meet_their_neighbours() {
        let a = hill("a", [0.0, 0.0], [8.0, 8.0], |x, z| 0.1 * x + 0.05 * z);
        let b = hill("b", [8.0, 0.0], [16.0, 8.0], |x, z| 0.1 * x + 0.05 * z);
        Layout::from_json(&layout_json(&[a.clone(), b], &[])).unwrap();
        let ledge = hill("b", [8.0, 0.0], [16.0, 8.0], |x, z| {
            0.1 * x + 0.05 * z + z * 0.12
        });
        let e = err(&layout_json(&[a.clone(), ledge], &[]));
        assert!(e.contains("ledge"), "{e}");
        // A flat door at the hill's edge, level with it: fine; a cellar
        // 5 m below touching it: a wall.
        let door = Surface {
            kind: SurfaceKind::Door,
            ..flat("door", [-2.0, 2.0], [0.0, 4.0], 0.15)
        };
        Layout::from_json(&layout_json(&[a.clone(), door], &[])).unwrap();
        let cellar = flat("cellar", [-6.0, 0.0], [0.0, 8.0], -5.0);
        Layout::from_json(&layout_json(&[a.clone(), cellar], &[])).unwrap();
        let tilted = flat("tilted", [-6.0, 0.0], [0.0, 8.0], 0.0);
        let e = err(&layout_json(&[a, tilted], &[]));
        assert!(e.contains("ledge"), "{e}");
    }
