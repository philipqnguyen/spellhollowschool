//! The castle layout: the walkable surfaces of the world, loaded from
//! `data/world/layout.json`. The same file drives the Blender greybox generator
//! (walls are built around surface edges, with openings where surfaces connect),
//! the server's movement validation and the client's collision response.
//!
//! Model: the walkable world is a set of axis-aligned rectangular [`Surface`]s.
//! Flat surfaces have one height; stairs/ramps rise linearly along one axis.
//! A point is walkable if it lies inside a surface; its ground height comes
//! from that surface. Two surfaces connect where they overlap or share an edge
//! at heights within `MoveParams::step_height` of each other. Rooms normally
//! connect to each other only through small `Door` surfaces that bridge the gap
//! in their walls.
//!
//! The types here are the file format. Runtime queries (spatial index, ground
//! height, levels) live in [`crate::world::World`], which is built from a
//! validated [`Layout`].
//!
//! Additions, all optional so older files still load:
//!
//! - **House gates.** A surface with `house` set (a lower-case house id such as
//!   `"roarwing"`, see `protocol::House::id`) is walkable only for that house:
//!   a common room and the doorway into it. [`Layout::for_house`] drops the
//!   surfaces gated to other houses, so for everyone else the gate is simply a
//!   wall. The server validates each player's moves against their house's view
//!   (the same rule the client predicts with), which is how it enforces the
//!   gate. Spawns must stand on ungated ground.
//! - **Interactables** ([`Interactable`]): doors and other things a player
//!   uses with `ClientMsg::Interact`, such as the dorm door in each common room
//!   (`dorm_door`) and the way out of a dorm (`dorm_exit`).
//! - **Placeable areas** ([`PlaceArea`]): where furniture may stand in an
//!   instance layout (see [`crate::placement`]).
//!
//! Adds interactable kinds: `find_spot` (exploration finds,
//! [`crate::finds`]), the crafting stations `craft_charms` and
//! `craft_transfiguration` (one each per common room, gated to its house)
//! and `cauldron` (the Potions classroom), and `owl_exchange` (the Exchange
//! counter in the Entrance Hall). [`InteractableKind::station`] maps the
//! station kinds to `protocol::StationKind`.
//!
//! Adds the interactable kinds `class_door` (a classroom door in
//! the castle: during a session's join window it admits students into a
//! section of the class, `data/classes/schedule.json` names the door) and
//! `instance_exit` (the way out of a class or arena instance, like
//! `dorm_exit`), and **areas** ([`Area`]): named boxes of the castle with a
//! purpose, such as the Dueling Club (`dueling_club`), where players may
//! challenge each other and watch duels (`data/dueling/venues.json`).
//!
//! Adds the kind `notice_board` (a common room's board, gated to its
//! house: the client opens the House Cup panel and the house's next classes).
//!
//! Adds **heightfields** ([`Heights`]): a grounds surface may carry
//! `heights`, a grid of ground heights every `step` metres covering its
//! rectangle, read with bilinear blending. The rectangle stays the walk limit
//! (so it stays convex for navigation); only the height inside it varies.
//! Validation caps the slope between neighbouring samples
//! ([`MAX_GROUND_SLOPE`]) and refuses a ledge where a heightfield surface meets
//! a neighbour it connects to ([`Layout::validate`]). The grounds' heights are
//! generated by `tools/blender/terrain_layout.py`, which also writes the same
//! values per cell to `data/world/terrain/<cell>.json` for the terrain mesh.
//!
//! Adds **flying**: the area kinds [`AreaKind::Airspace`] (boxes of
//! open sky where a broom may fly) and [`AreaKind::NoFly`] (boxes no broom may
//! enter: the castle, the Owl Loft site, the Groundskeeper's Cottage, the pitch's stands and
//! towers), read by `crate::flight`; and **ring courses** ([`Ring`], the
//! `rings` of an instance layout: the Flying class's hoops, which
//! `protocol::BeatPrompt::Ring` names by their index here).
//!
//! Adds **moving staircases**: a stair surface may carry `moving`
//! ([`Moving`]): it is one of the two positions, A or B, of a Grand Staircase
//! flight that swings between them on the shared schedule of
//! `data/world/stairs.json` ([`crate::stairs`]). Each flight has exactly one
//! surface at each position; only one of them exists at a time
//! ([`Layout::for_stairs`]). Bridges ([`SurfaceKind::Bridge`]) may slope like
//! stairs (the covered bridge to the stone circle), and the interactable kind
//! `owl_mail` (the Owl Loft: the client opens the mail panel).
//!
//! Adds **secrets**: a surface may carry `secret: true` (the five
//! hidden passages, their walk-through doors included; `data/world/secrets.json`
//! groups them, [`crate::secrets`]). A secret surface is ordinary ground for
//! moving (anyone may walk it, the load-test bots too), but the Monstra Viam
//! trail never routes over one ([`Surface::secret`], `nav`), no key place
//! stands on one, and the map draws one only after its secret is found.
//! The area kind [`AreaKind::PaceMark`] marks the two ends of the
//! seventh-floor east corridor's blank wall (the Wishing Room's
//! pacing, [`crate::wishing_room`]), and the interactable kind
//! `wishing_room_door` the door that appears there.
//!
//! **Instance layouts** use this same schema, one file per instance kind in
//! `data/world/instances/<id>.json`: the four dorm shells are `dorm_<house id>`
//! (`dorm_roarwing`, `dorm_burrowsby`, `dorm_skytalon`, `dorm_serpentyne`).
//! Each has a spawn (where entering players appear), a `dorm_exit`
//! interactable and its placeable areas. Their cell ids stay neutral
//! (`dorm_house_a` ...) because cells become asset file names.

